"""Weighted multi-point representation of each JEPX area.

Loads ``data/reference/area_points_capacity.csv`` (generated by
the area-points build script (``03_build_area_points.py`` in the
replication package) from the METI
FIT-portal operating-capacity tables) into area -> [(prefecture, lat, lon,
weight)] lists. Weights are the prefecture's PV operating-capacity share
WITHIN its area, so they sum to 1 per area by construction; a tolerance check
enforces that on every load rather than trusting the file.

Two vintages ship: "2024-09" (primary; static weights aligned with the panel
start) and "2025-12" (sensitivity). Split prefectures are assigned whole to
their primary TSO; the assignment is pre-committed in
docs/research/2026-08-03_phase74_cw_precommit.md.
"""

from __future__ import annotations

import csv
from dataclasses import dataclass
from pathlib import Path

from alg.config import EpfConfig

_CSV = "data/reference/area_points_capacity.csv"
_WEIGHT_TOL = 1e-4


@dataclass(frozen=True)
class AreaPoint:
    prefecture: str
    lat: float
    lon: float
    weight: float


def area_points(vintage: str = "2024-09",
                csv_path: Path | None = None) -> dict[str, list[AreaPoint]]:
    """Area -> capacity-weighted prefecture points for one weight vintage."""
    path = csv_path or (EpfConfig().project_root / _CSV)
    out: dict[str, list[AreaPoint]] = {}
    with path.open(encoding="utf-8") as f:
        rows = list(csv.DictReader(line for line in f
                                   if not line.startswith("#")))
    for r in rows:
        if r["vintage"] != vintage:
            continue
        out.setdefault(r["area"], []).append(AreaPoint(
            prefecture=r["prefecture"], lat=float(r["lat"]),
            lon=float(r["lon"]), weight=float(r["weight_in_area"])))
    if not out:
        known = sorted({r["vintage"] for r in rows})
        msg = f"vintage {vintage!r} not in {path} (has {known})"
        raise ValueError(msg)
    for area, pts in out.items():
        s = sum(p.weight for p in pts)
        if abs(s - 1.0) > _WEIGHT_TOL:
            msg = f"{area}: weights sum to {s}, expected 1"
            raise ValueError(msg)
    return out
